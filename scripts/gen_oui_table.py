#!/usr/bin/env python3
"""
Generate apps/room-scanner/src/oui_table.h: the MAC address prefixes (OUI)
of camera makers and of the WiFi chips cheap cameras are built on, from the
IEEE MA-L registry.

    python scripts/gen_oui_table.py oui.txt > apps/room-scanner/src/oui_table.h

oui.txt is https://standards-oui.ieee.org/oui/oui.txt (also shipped in the
`netaddr` Python package as netaddr/eui/oui.txt). Vendors and their weight
are listed in VENDORS below.
"""

import re
import sys

# (short name shown on the display, category, regex on the IEEE organization name)
# CAMERA:     makes (mostly) security cameras, doorbells and recorders
# CAMERA_SOC: chips made for cameras
# IOT:        WiFi chips / platforms of cheap smart devices, hidden cameras included
VENDORS = [
    ("Hikvision", "CAMERA", r"hikvision"),
    ("Ezviz", "CAMERA", r"ezviz"),
    ("Dahua", "CAMERA", r"dahua"),
    ("Uniview", "CAMERA", r"uniview"),
    ("Hanwha", "CAMERA", r"hanwha techwin"),
    ("Axis", "CAMERA", r"^axis communications"),
    ("Vivotek", "CAMERA", r"vivotek"),
    ("Amcrest", "CAMERA", r"amcrest"),
    ("Reolink", "CAMERA", r"reolink"),
    ("Lorex", "CAMERA", r"lorex"),
    ("Wyze", "CAMERA", r"wyze"),
    ("Ring", "CAMERA", r"^ring llc"),
    ("Blink", "CAMERA", r"^blink by amazon"),
    ("Arlo", "CAMERA", r"^arlo technology"),
    ("YI", "CAMERA", r"shanghai xiaoyi"),
    ("Ingenic", "CAMERA_SOC", r"ingenic semiconductor"),
    ("Goke", "CAMERA_SOC", r"goke microelectronics"),
    ("Espressif", "IOT", r"espressif"),
    ("Tuya", "IOT", r"tuya smart"),
    ("Beken", "IOT", r"beken corporation"),
    ("Bilian", "IOT", r"shenzhen bilian"),
    ("HiSilicon", "IOT", r"hisilicon"),
]

CATEGORIES = ["CAMERA", "CAMERA_SOC", "IOT"]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    patterns = [(name, cat, re.compile(regex, re.I)) for name, cat, regex in VENDORS]
    entries = {}
    with open(sys.argv[1], encoding="utf-8", errors="replace") as f:
        for line in f:
            match = re.match(r"^([0-9A-F]{6})\s+\(base 16\)\s+(.*)$", line.strip())
            if not match:
                continue
            oui, org = int(match.group(1), 16), match.group(2).strip()
            for index, (_name, _cat, regex) in enumerate(patterns):
                if regex.search(org):
                    entries[oui] = index
                    break

    used = sorted(set(entries.values()))
    counts = {i: sum(1 for v in entries.values() if v == i) for i in used}
    missing = [VENDORS[i][0] for i in range(len(VENDORS)) if i not in counts]
    if missing:
        sys.exit("no OUIs found for: " + ", ".join(missing))

    out = []
    out.append("// Generated by scripts/gen_oui_table.py from the IEEE MA-L registry - do not edit")
    out.append("#pragma once")
    out.append("")
    out.append('#include "roomscan.h"')
    out.append("")
    out.append("static const oui_vendor_t OUI_VENDORS[] = {")
    for name, cat, _regex in VENDORS:
        out.append('    {"%s", VENDOR_%s}, // OUIs: %d' % (name, cat, counts[VENDORS.index((name, cat, _regex))]))
    out.append("};")
    out.append("")
    out.append("/* OUI << 8 | index into OUI_VENDORS, sorted */")
    out.append("static const uint32_t OUI_TABLE[] = {")
    items = ["0x%08X" % (oui << 8 | index) for oui, index in sorted(entries.items())]
    for i in range(0, len(items), 6):
        out.append("    " + ", ".join(items[i:i + 6]) + ",")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
