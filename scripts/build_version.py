"""
PlatformIO pre-build script: writes src/firmware_version.h with the
firmware version shown in the web panel.

The version is `git describe --tags --always --dirty` of the source tree:
a release tag (v1.2), a tag plus commits (v1.2-3-gabc1234), or the short
commit hash; "-dirty" marks uncommitted changes. The header is only
rewritten when the version changes, so only main.cpp is recompiled.
"""

import os
import subprocess

Import("env")  # noqa: F821 - provided by PlatformIO (SCons)


def firmware_version(project_dir):
    try:
        return subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


project_dir = env.subst("$PROJECT_DIR")
version = firmware_version(project_dir)
header = os.path.join(project_dir, "src", "firmware_version.h")
content = (
    "// Generated by scripts/build_version.py - do not edit\n"
    "#pragma once\n"
    '#define FIRMWARE_VERSION "%s"\n' % version.replace("\\", "").replace('"', "")
)

try:
    with open(header) as f:
        current = f.read()
except OSError:
    current = None

if current != content:
    with open(header, "w") as f:
        f.write(content)
print("Firmware version: %s" % version)
