/* Arrows at their CP437 codes: 0x18 up, 0x19 down, 0x1A right, 0x1B left */
static const uint8_t arrow_glyphs[4][8] = {
    {0x18, 0x3C, 0x7E, 0x18, 0x18, 0x18, 0x18, 0x00}, // up
    {0x18, 0x18, 0x18, 0x18, 0x7E, 0x3C, 0x18, 0x00}, // down
    {0x10, 0x30, 0x70, 0x7F, 0x7F, 0x70, 0x30, 0x10}, // right
    {0x04, 0x06, 0x07, 0x7F, 0x7F, 0x07, 0x06, 0x04}, // left
};

bool lcd_init(void)
{
  if (!display_mutex)
    display_mutex = xSemaphoreCreateRecursiveMutex();

  // Backlight off until the first screen is drawn
  gpio_config_t bk_gpio_config = {};
  bk_gpio_config.pin_bit_mask = 1ULL << LCD_BL_PIN;
  bk_gpio_config.mode = GPIO_MODE_OUTPUT;
  gpio_config(&bk_gpio_config);
  gpio_set_level((gpio_num_t)LCD_BL_PIN, 0);

  spi_bus_config_t buscfg = {};
  buscfg.mosi_io_num = LCD_MOSI_PIN;
  buscfg.miso_io_num = -1;
  buscfg.sclk_io_num = LCD_SCLK_PIN;
  buscfg.quadwp_io_num = -1;
  buscfg.quadhd_io_num = -1;
  buscfg.max_transfer_sz = LCD_H_RES * LCD_V_RES * sizeof(uint16_t);
  ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST, &buscfg, SPI_DMA_CH_AUTO));

  esp_lcd_panel_io_spi_config_t io_config = {};
  io_config.cs_gpio_num = LCD_CS_PIN;
  io_config.dc_gpio_num = LCD_DC_PIN;
  io_config.spi_mode = 0;
  io_config.pclk_hz = LCD_PIXEL_CLK;
  io_config.trans_queue_depth = 10;
  io_config.lcd_cmd_bits = 8;
  io_config.lcd_param_bits = 8;
  ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)SPI2_HOST, &io_config, &lcd_io_handle));

  esp_lcd_panel_dev_config_t panel_config = {};
  panel_config.reset_gpio_num = LCD_RST_PIN;
  panel_config.rgb_ele_order = LCD_RGB_ELEMENT_ORDER_BGR;
  panel_config.bits_per_pixel = 16;
  ESP_ERROR_CHECK(esp_lcd_new_panel_st7789(lcd_io_handle, &panel_config, &lcd_panel_handle));

  esp_lcd_panel_reset(lcd_panel_handle);
  vTaskDelay(pdMS_TO_TICKS(100));
  esp_lcd_panel_init(lcd_panel_handle);
  vTaskDelay(pdMS_TO_TICKS(100));

  // ST7789V2 of the Cardputer: inverted colors, 135x240 window at (52, 40),
  // landscape (swapped and mirrored)
  esp_lcd_panel_invert_color(lcd_panel_handle, true);
  esp_lcd_panel_set_gap(lcd_panel_handle, 40, 52);
  esp_lcd_panel_swap_xy(lcd_panel_handle, true);
  esp_lcd_panel_mirror(lcd_panel_handle, true, false);
  esp_lcd_panel_disp_on_off(lcd_panel_handle, true);
  vTaskDelay(pdMS_TO_TICKS(100));

  framebuffer = (uint16_t *)heap_caps_malloc(LCD_V_RES * LCD_H_RES * sizeof(uint16_t), MALLOC_CAP_DMA);
  if (!framebuffer)
  {
    ESP_LOGE(TAG, "Failed to allocate the framebuffer");
    return false;
  }
  ESP_LOGI(TAG, "Display ready: %dx%d", LCD_V_RES, LCD_H_RES);
  return true;
}

bool lcd_ready(void) { return framebuffer != NULL; }

void display_lock(void)
{
  if (display_mutex)
    xSemaphoreTakeRecursive(display_mutex, portMAX_DELAY);
}

void display_unlock(void)
{
  if (display_mutex)
    xSemaphoreGiveRecursive(display_mutex);
}

void lcd_backlight(bool on) { gpio_set_level((gpio_num_t)LCD_BL_PIN, on ? 1 : 0); }

void lcd_flush(void)
{
  if (!lcd_panel_handle || !framebuffer)
    return;
  esp_lcd_panel_draw_bitmap(lcd_panel_handle, 0, 0, LCD_V_RES, LCD_H_RES, framebuffer);
}

void lcd_fill_screen(uint16_t color)
{
  if (!framebuffer)
    return;
  for (int i = 0; i < LCD_V_RES * LCD_H_RES; i++)
    framebuffer[i] = color;
}

void lcd_fill_rect(int x, int y, int w, int h, uint16_t color)
{
  if (!framebuffer)
    return;
  int x0 = x < 0 ? 0 : x;
  int y0 = y < 0 ? 0 : y;
  int x1 = x + w > LCD_V_RES ? LCD_V_RES : x + w;
  int y1 = y + h > LCD_H_RES ? LCD_H_RES : y + h;
  for (int py = y0; py < y1; py++)
    for (int px = x0; px < x1; px++)
      framebuffer[py * LCD_V_RES + px] = color;
}

void lcd_fill_circle(int x, int y, int radius, uint16_t color)
{
  if (!framebuffer)
    return;
  for (int dy = -radius; dy <= radius; dy++)
    for (int dx = -radius; dx <= radius; dx++)
      if (dx * dx + dy * dy <= radius * radius && x + dx >= 0 && x + dx < LCD_V_RES && y + dy >= 0 &&
          y + dy < LCD_H_RES)
        framebuffer[(y + dy) * LCD_V_RES + (x + dx)] = color;
}

void lcd_draw_char(int x, int y, char c, uint16_t color, uint16_t bg_color)
{
  const uint8_t *glyph;
  if (c >= 0x18 && c <= 0x1B)
    glyph = arrow_glyphs[c - 0x18];
  else if (c >= 32 && c <= 127)
    glyph = font8x8[c - 32];
  else
    return;
  if (!framebuffer)
    return;

  for (int py = 0; py < FONT_H; py++)
  {
    uint8_t line = glyph[py];
    for (int px = 0; px < FONT_W; px++)
    {
      int screen_x = x + px;
      int screen_y = y + py;
      if (screen_x >= 0 && screen_x < LCD_V_RES && screen_y >= 0 && screen_y < LCD_H_RES)
        framebuffer[screen_y * LCD_V_RES + screen_x] = (line & (1 << px)) ? color : bg_color;
    }
  }
}

void lcd_draw_string(int x, int y, const char *str, uint16_t color, uint16_t bg_color)
{
  for (; *str; str++, x += FONT_W)
    lcd_draw_char(x, y, *str, color, bg_color);
}

