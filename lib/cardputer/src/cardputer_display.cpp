void ui_draw_frame(int x, int y, int w, int h)
{
  lcd_fill_rect(x, y, w, 1, THEME_BORDER);
  lcd_fill_rect(x, y + h - 1, w, 1, THEME_BORDER);
  lcd_fill_rect(x, y, 1, h, THEME_BORDER);
  lcd_fill_rect(x + w - 1, y, 1, h, THEME_BORDER);
}

void ui_draw_title_bar(const char *title)
{
  lcd_fill_rect(0, 0, LCD_V_RES, 18, THEME_BAR);
  lcd_draw_string(5, 5, title, THEME_TITLE, THEME_BAR);
  ui_draw_battery(236, 4, THEME_BAR);
}

void ui_draw_battery(int right_x, int y, uint16_t bg_color)
{
  int level = battery_percent();
  if (level < 0)
    return;
  uint16_t color = level <= 15 ? THEME_ERROR : THEME_OK; // red when low

  // 18x9 outline with a 2x5 terminal on the right
  int x = right_x - 20;
  lcd_fill_rect(x, y, 18, 9, color);
  lcd_fill_rect(x + 1, y + 1, 16, 7, bg_color);
  lcd_fill_rect(x + 18, y + 2, 2, 5, color);
  lcd_fill_rect(x + 2, y + 2, 14 * level / 100, 5, color);

  char text[12];
  snprintf(text, sizeof(text), "%d%%", level);
  lcd_draw_string(x - 4 - (int)strlen(text) * FONT_W, y + 1, text, color, bg_color);
}

void ui_draw_signal_bars(int x, int y, int rssi)
{
  int bars = 1;
  if (rssi > -70)
    bars = 4;
  else if (rssi > -80)
    bars = 3;
  else if (rssi > -90)
    bars = 2;

  // Heights 2, 4, 6, 8, aligned at the bottom
  for (int i = 0; i < 4; i++)
  {
    int bar_height = 2 + i * 2;
    lcd_fill_rect(x + i * 4, y + 8 - bar_height, 3, bar_height, i < bars ? THEME_OK : GRUV_BG2);
  }
}

void ui_draw_rssi_meter(int x, int y, int w, int h, int rssi, uint16_t color)
{
  int level = rssi + 100; // -100 dBm = empty, -30 dBm = full
  level = level < 0 ? 0 : (level > 70 ? 70 : level);
  ui_draw_frame(x, y, w, h);
  lcd_fill_rect(x + 1, y + 1, w - 2, h - 2, THEME_BG);
  lcd_fill_rect(x + 2, y + 2, (w - 4) * level / 70, h - 4, color);
}
